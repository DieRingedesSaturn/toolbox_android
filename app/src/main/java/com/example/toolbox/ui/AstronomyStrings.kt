fun ToolboxStrings.compassDirection(azimuth: Double): String {
    val norm = (azimuth % 360 + 360) % 360
    val index = (((norm + 22.5) % 360) / 45).toInt()
    return if (chinese) {
        listOf("北", "东北", "东", "东南", "南", "西南", "西", "西北")[index]
    } else {
        listOf("N", "NE", "E", "SE", "S", "SW", "W", "NW")[index]
    }
}

